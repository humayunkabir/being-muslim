package app.beingmuslim.android.ui.theme

import androidx.compose.material3.ColorScheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.luminance
import kotlin.math.max
import kotlin.math.min
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Contrast of the colour pairs the app actually puts text on
 * (`docs/DESIGN_STANDARDS.md` §7, `docs/PRODUCT_REQUIREMENTS.md` §13).
 *
 * The app ships no brand palette yet, so it uses Material 3's baseline schemes
 * below Android 12 and the system's dynamic palette above it
 * (`docs/DESIGN_STANDARDS.md` §1, §4). The dynamic palette is generated by the
 * platform and cannot be pinned here; this test covers the baseline scheme the
 * app falls back to and the pairs its own composables use. WCAG 2.2 AA wants
 * 4.5:1 for normal text and 3:1 for non-text UI.
 */
class ThemeContrastTest {

    @Test
    fun lightSchemeTextMeetsAa() {
        assertTextPairsMeetAa(lightColorScheme())
    }

    @Test
    fun darkSchemeTextMeetsAa() {
        assertTextPairsMeetAa(darkColorScheme())
    }

    @Test
    fun theDialsOutlineMeetsTheNonTextMinimum() {
        listOf(lightColorScheme(), darkColorScheme()).forEach { scheme ->
            assertTrue(
                "outline on background is below 3:1",
                contrast(scheme.outline, scheme.background) >= NON_TEXT_MINIMUM,
            )
        }
    }

    private fun assertTextPairsMeetAa(scheme: ColorScheme) {
        // Body and headings.
        assertRatio(scheme.onBackground, scheme.background, "onBackground on background", scheme)
        assertRatio(scheme.onSurface, scheme.surface, "onSurface on surface", scheme)
        // Secondary copy and captions (bodySmall on the surface).
        assertRatio(scheme.onSurfaceVariant, scheme.surface, "onSurfaceVariant on surface", scheme)
        // Error copy, and the report's retry line.
        assertRatio(scheme.error, scheme.surface, "error on surface", scheme)
        // Text buttons use primary as their content colour.
        assertRatio(scheme.primary, scheme.surface, "primary on surface", scheme)
        // Filled buttons.
        assertRatio(scheme.onPrimary, scheme.primary, "onPrimary on primary", scheme)
        // Cards (the setup help) use the highest container role.
        assertRatio(scheme.onSurface, scheme.surfaceContainerHighest, "onSurface on surfaceContainerHighest", scheme)
        assertRatio(scheme.primary, scheme.surfaceContainerHighest, "primary on surfaceContainerHighest", scheme)
        // Alert dialogs (delete, notification explanation) use the high role.
        assertRatio(scheme.onSurface, scheme.surfaceContainerHigh, "onSurface on surfaceContainerHigh", scheme)
        assertRatio(scheme.onSurfaceVariant, scheme.surfaceContainerHigh, "onSurfaceVariant on surfaceContainerHigh", scheme)
        assertRatio(scheme.primary, scheme.surfaceContainerHigh, "primary on surfaceContainerHigh", scheme)
        assertRatio(scheme.error, scheme.surfaceContainerHigh, "error on surfaceContainerHigh", scheme)
    }

    private fun assertRatio(
        foreground: Color,
        background: Color,
        label: String,
        scheme: ColorScheme,
    ) {
        val ratio = contrast(foreground, background)
        assertTrue(
            "$label is $ratio:1, below $TEXT_MINIMUM:1 ($scheme)",
            ratio >= TEXT_MINIMUM,
        )
    }

    /** WCAG relative-luminance contrast ratio. */
    private fun contrast(foreground: Color, background: Color): Double {
        val a = foreground.luminance().toDouble()
        val b = background.luminance().toDouble()
        return (max(a, b) + 0.05) / (min(a, b) + 0.05)
    }

    private companion object {
        const val TEXT_MINIMUM = 4.5
        const val NON_TEXT_MINIMUM = 3.0
    }
}
